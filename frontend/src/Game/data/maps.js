export function getMapById(id) {
  return CAMPUS_MAPS.find((map) => map.id === id) || CAMPUS_MAPS[0];
}

export function isMapUnlocked(map, level = 1) {
  return Math.max(1, Number(level) || 1) >= (map?.unlockLevel || 1);
}

export function resolveMap(id, level = 1) {
  const map = getMapById(id);
  return isMapUnlocked(map, level) ? map : CAMPUS_MAPS[0];
}
